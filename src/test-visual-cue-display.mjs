import assert from 'node:assert/strict';
import {cueForReply,replyTopic,normalizeVisualCueMode,VISUAL_CUE_ASSET,VISUAL_CUE_MODE_KEY} from './visual-cue-display.js';
const f=(scene,english,topic)=>cueForReply({scene,topic,english});
assert.equal(normalizeVisualCueMode(null),'emma');
assert.equal(normalizeVisualCueMode('noise'),'emma');
assert.equal(normalizeVisualCueMode('illustration'),'illustration');
assert.equal(replyTopic({scene:'combined:book:praise',english:'Book time!'}),'book');
assert.equal(replyTopic({scene:'interaction:praise',english:'Good job!'}),null);
assert.equal(f('milk','Want a little sip?')?.id,'milk');
assert.equal(f('combined:milk:invitation','Ready for some milk?')?.id,'milk');
assert.equal(f('book','Turn the page.')?.id,'book');
assert.equal(f('combined:book:praise','What a nice book!')?.id,'book');
assert.equal(f('hands','Clap, clap!')?.id,'clap');
assert.equal(f('hands','Your hands are warm.'),null);
assert.equal(f('hands','Can you wave?'),null);
assert.equal(f('feet','Kick, kick!')?.id,'kick');
assert.equal(f('feet','Little toes!'),null);
assert.equal(f('cry','It is okay.'),null);
assert.equal(f('generic','I am right here.'),null);
assert.equal(f('interaction:encouragement','Good job!'),null);
assert.equal(f('combined:cry:reassurance','I am right here.'),null);
assert.equal(cueForReply({topic:'book',english:''})?.id,'book');
assert.equal(cueForReply({topic:'book'}),null);
assert.match(VISUAL_CUE_ASSET,/\.webp$/);
assert.match(VISUAL_CUE_MODE_KEY,/visual_cue/);
console.log('Visual Cue display: 20 selection/fallback cases OK');
