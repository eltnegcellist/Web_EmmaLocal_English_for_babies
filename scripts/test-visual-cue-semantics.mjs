import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {currentBankRows,createVisualCueData,inferVisualCue} from './build-visual-cue-data.mjs';
import {buildVisualAssetPlan} from './build-visual-cue-assets.mjs';
import {auditVisualCueSemantics} from './audit-visual-cue-semantics.mjs';
const load=name=>JSON.parse(readFileSync(new URL('../shared/'+name,import.meta.url),'utf8'));
const phrases=load('visual-cue-phrases.json').rows;
const current=load('visual-cue-assignments.draft.json').assignments;
const overrides=load('visual-cue-reviewed-overrides.json').overrides;
const registry=load('visual-cue-namespaces.json');
const plan=buildVisualAssetPlan(registry);
const storedPlan=load('visual-cue-asset-plan.json');
assert.deepEqual(storedPlan,plan);
assert.equal(plan.primitives.length,31);
assert.equal(plan.firstPrototypes.length,12);
assert.equal(plan.bindings.length,registry.cues.length);
for(const binding of plan.bindings){
 assert.ok(binding.primitives.length);
 for(const id of binding.primitives)assert.ok(plan.primitives.some(x=>x.id===id),'Unknown reusable primitive '+id);
}
const rebuilt=createVisualCueData(currentBankRows(),phrases,current,overrides);
assert.equal(rebuilt.snapshot.rows.length,914);
assert.equal(rebuilt.draft.assignments.length,914);
assert.equal(rebuilt.draft.assignments.filter(a=>a.reviewStatus==='reviewed').length,overrides.length);
assert.equal(rebuilt.draft.assignments.filter(a=>a.sourceKind==='press' && a.sentenceCues.length===3).length,110);
const byId=new Map(rebuilt.draft.assignments.map(a=>[a.phraseId,a]));
const assertCue=(id,cue)=>assert.equal(byId.get(id)?.primaryCue,cue,id);
assertCue('vc_000020','social.greeting');
assertCue('vc_000039','subject.milk');
assertCue('vc_000040','subject.milk');
assertCue('vc_000058','action.wake');
assertCue('vc_000059','action.wake');
assertCue('vc_000061','action.wake');
assertCue('vc_000112','social.reassurance');
assertCue('vc_000118','social.reassurance');
assertCue('vc_000128','subject.tummy');
assertCue('vc_000130','subject.tummy');
assertCue('vc_000153','subject.rain');
assertCue('vc_000262','dialogue.finish-check');
assertCue('vc_000368','dialogue.finish-check');
assertCue('vc_000383','social.reassurance');
assertCue('vc_000388','social.reassurance');
assertCue('vc_000690','subject.hands');
assert.equal(inferVisualCue('Little tummy.','press','tummy',true).primaryCue,'subject.tummy');
assert.equal(inferVisualCue('Mmm, yummy!','press','milk',true).primaryCue,'emma.neutral');
assert.equal(inferVisualCue('Warm and cozy.','press','hug',true).primaryCue,'emma.neutral');
assert.equal(inferVisualCue('Look, look!','press','book',true).primaryCue,'attention.look');
assert.equal(inferVisualCue('Nice and gentle.','press','cry',true).primaryCue,'social.reassurance');
assert.equal(inferVisualCue('Did you rest well? You are awake.','topic','wake').primaryCue,'action.wake');
assert.equal(inferVisualCue('Rain on the window! Tap, tap, tap.','topic','rain').primaryCue,'subject.rain');
assert.equal(inferVisualCue('Are you upset? I am right here.','topic','cry').primaryCue,'social.reassurance');
assert.equal(inferVisualCue('Is that a burp?','topic','tummy').primaryCue,'subject.tummy');
const mismatched=structuredClone(overrides);
mismatched[0].text='Completely different English sentence.';
assert.throws(()=>createVisualCueData(currentBankRows(),phrases,current,mismatched),/Reviewed cue override changed text/);
const findings=auditVisualCueSemantics(rebuilt.draft.assignments,overrides);
assert.equal(findings.blockers.length,0,JSON.stringify(findings.blockers.slice(0,3)));
assert.deepEqual(findings,load('visual-cue-semantic-audit.json'));
assert.ok(findings.reviewQueue.length>0,'Outstanding human review queue should be explicit');
console.log(JSON.stringify({passed:true,sets:rebuilt.draft.assignments.length,reviewed:overrides.length,cautions:findings.reviewQueue.length,reusablePrimitives:plan.primitives.length}));
