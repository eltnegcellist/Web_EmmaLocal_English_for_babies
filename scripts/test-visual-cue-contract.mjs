import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {validateVisualCues} from './validate-visual-cues.mjs';
const load=p=>JSON.parse(readFileSync(new URL(p,import.meta.url),'utf8'));
const sample=load('../shared/visual-cue-contract.example.json');
const taxonomy=load('../shared/visual-cue-namespaces.json');
const schema=load('../shared/visual-cue-contract.schema.json');
assert.equal(schema.properties.schemaVersion.const,2);
assert.equal(schema.$defs.assignment.required.includes('sourceKind'),true);
const change=fn=>{const d=structuredClone(sample);fn(d);return d;};
const errs=(d,strict=false)=>validateVisualCues(d,taxonomy,{strict});
const bad=(type,d,strict=false)=>assert.ok(errs(d,strict).some(e=>e.type===type),type);
assert.deepEqual(errs(sample),[]);assert.deepEqual(errs(sample,true),[]);
bad('phrase_id_duplicate',change(x=>x.assignments[1].phraseId=x.assignments[0].phraseId));
bad('phrase_id_invalid',change(x=>x.assignments[0].phraseId='topic:milk:1'));
bad('namespace_unknown',change(x=>x.assignments[0].primaryCue='missing.whatever'));
bad('cue_duplicate',change(x=>x.assignments[0].secondaryCues=['action.sip']));
bad('sentence_index_invalid_or_duplicate',change(x=>x.assignments[1].sentenceCues[0].index=1));
bad('press_sentence_incomplete',change(x=>x.assignments[1].sentenceCues.pop()),true);
bad('review_pending',change(x=>x.assignments[0].reviewStatus='generated'),true);
bad('fingerprint_invalid',change(x=>x.assignments[0].textFingerprint='short'));
assert.deepEqual(errs(change(x=>x.assignments[0].text='New English while ID remains')),[]);
console.log('Visual Cue design-only validation checks passed');
